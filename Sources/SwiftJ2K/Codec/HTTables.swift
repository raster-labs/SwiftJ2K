    private static func buildDecodeTable(from spec: [CxtVLCSpecTuple]) -> [CxtVLCDecodeEntry] {
        var table = [CxtVLCDecodeEntry](
            repeating: CxtVLCDecodeEntry(rho: 0, uOff: 0, embKnown: 0, embOne: 0, bitLength: 0),
            count: 8 * 128
        )
        for tuple in spec {
            let base = Int(tuple.context) << 7
            let step = 1 << Int(tuple.bitLength)
            let decoded = CxtVLCDecodeEntry(
                rho: tuple.rho,
                uOff: tuple.uOff,
                embKnown: tuple.embKnown,
                embOne: tuple.embOne,
                bitLength: tuple.bitLength
            )
            var suffix = Int(tuple.codeword)
            while suffix < 128 {
                table[base | suffix] = decoded
                suffix += step
            }
        }
        return table
    }

    private static func buildEncodeTable(from spec: [CxtVLCSpecTuple]) -> [CxtVLCEncodeEntry] {
        // Group normative tuples by `(c_q << 4) | rho_q` for direct candidate selection per Annex F.3:
        var byContextAndRho = [[CxtVLCSpecTuple]](repeating: [], count: 8 * 16)
        for tuple in spec {
            let bucket = (Int(tuple.context) << 4) | Int(tuple.rho)
            byContextAndRho[bucket].append(tuple)
        }

        var table = [CxtVLCEncodeEntry](
            repeating: CxtVLCEncodeEntry(codeword: 0, bitLength: 0, embKnown: 0),
            count: 8 * 16 * 16
        )

        for context in 0..<8 {
            for rho in 0..<16 {
                // Insignificant all-zero-context quads (`c_q == 0 && rho_q == 0`) emit no VLC bits (Annex F.3).
                if context == 0 && rho == 0 {
                    continue
                }
                let candidates = byContextAndRho[(context << 4) | rho]
                for emb in 0..<16 {
                    // Valid full EMB patterns are subsets of `rho`; when `rho == 0`, only `emb == 0` occurs.
                    if (emb & ~rho) != 0 {
                        continue
                    }
                    let uOff: UInt8 = emb == 0 ? 0 : 1
                    let embByte = UInt8(emb)
                    var best: CxtVLCSpecTuple? = nil
                    var bestKnownBits = -1
                    for candidate in candidates {
                        guard candidate.uOff == uOff else { continue }
                        guard (embByte & candidate.embKnown) == candidate.embOne else { continue }
                        let knownBits = candidate.embKnown.nonzeroBitCount
                        if knownBits > bestKnownBits {
                            bestKnownBits = knownBits
                            best = candidate
                        }
                    }
                    if let selected = best {
                        let index = (context << 8) | (rho << 4) | emb
                        table[index] = CxtVLCEncodeEntry(
                            codeword: selected.codeword,
                            bitLength: selected.bitLength,
                            embKnown: selected.embKnown
                        )
                    }
                }
            }
        }
        return table
    }

