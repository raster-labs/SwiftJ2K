    /// Prefix, suffix, and extension bit-fields for a single U-VLC unsigned residual `u` (Table 3).
    package struct UVLCComponents: Sendable, Equatable {
        package let prefixBits: UInt8
        package let prefixLength: UInt8
        package let suffixBits: UInt8
        package let suffixLength: UInt8
        package let extensionBits: UInt8
        package let extensionLength: UInt8

        package static let empty = UVLCComponents(
            prefixBits: 0, prefixLength: 0,
            suffixBits: 0, suffixLength: 0,
            extensionBits: 0, extensionLength: 0
        )
    }

    /// Decomposes a non-negative residual `u` (`0...74`) into LSB-first U-VLC prefix, suffix, and
    /// extension codewords per ITU-T Rec. T.814 Clause 7.3.6, Table 3.
    @inline(__always)
    package static func encodeUVLC(_ u: Int) -> UVLCComponents {
        if u <= 0 {
            return .empty
        } else if u == 1 {
            // Prefix "1" -> LSB-first 0b1 (1 bit)
            return UVLCComponents(
                prefixBits: 0b001, prefixLength: 1,
                suffixBits: 0, suffixLength: 0,
                extensionBits: 0, extensionLength: 0
            )
        } else if u == 2 {
            // Prefix "01" -> first bit 0, second bit 1 -> LSB-first 0b10 (2 bits)
            return UVLCComponents(
                prefixBits: 0b010, prefixLength: 2,
                suffixBits: 0, suffixLength: 0,
                extensionBits: 0, extensionLength: 0
            )
        } else if u <= 4 {
            // Prefix "001" -> bits 0, 0, 1 -> LSB-first 0b100 (3 bits), 1-bit suffix (u - 3)
            return UVLCComponents(
                prefixBits: 0b100, prefixLength: 3,
                suffixBits: UInt8(u - 3), suffixLength: 1,
                extensionBits: 0, extensionLength: 0
            )
        } else if u <= 32 {
            // Prefix "000" -> 0b000 (3 bits), 5-bit suffix (u - 5) in 0...27
            return UVLCComponents(
                prefixBits: 0b000, prefixLength: 3,
                suffixBits: UInt8(u - 5), suffixLength: 5,
                extensionBits: 0, extensionLength: 0
            )
        } else {
            // u >= 33 (Table 3): prefix "000" (3 bits), 5-bit suffix 28 + ((u - 33) % 4), 4-bit ext (u - 33) / 4
            let offset = u - 33
            return UVLCComponents(
                prefixBits: 0b000, prefixLength: 3,
                suffixBits: UInt8(28 + (offset & 0x03)), suffixLength: 5,
                extensionBits: UInt8((offset >> 2) & 0x0F), extensionLength: 4
            )
        }
